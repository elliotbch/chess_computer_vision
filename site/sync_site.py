"""Copy into site/ what the static site (Pyodide, in the visitor's browser) runs and shows.

    python site/sync_site.py          # from the repository root, after any change to src/ or demo/app.py

- site/py/<module>.py   : the pipeline modules of src/, copied unchanged (site/tests/test_sync.py
                          checks they are byte-identical to src/);
- site/py/demo_glue.py  : the presentation functions of demo/app.py (replay steps, photo analysis,
                          drawings, error messages), extracted VERBATIM with `ast` and preceded by a
                          small header that replaces FastAPI's HTTPException (same status + message);
- site/py/manifest.json : list of the files the Web Worker writes into Pyodide's file system;
- site/assets/examples/ : example photos and games (copies of demo/static/examples/), plus, for
                          each example photo, frameXX.png: the pixels the FastAPI demo analyses
                          (its JPEG decoded by pip's OpenCV, libjpeg-turbo), saved losslessly. The
                          JPEG decoder of Pyodide's OpenCV rounds a few pixels differently, enough to
                          flip one borderline square of frame07; the site therefore analyses these
                          PNG files and shows the JPEG files as thumbnails. Writing them needs
                          opencv-python (as demo/sync_pipeline.py); without it they are kept as is;
- site/assets/catalog.json : example photos and games (EXAMPLES and GAMES of demo/app.py);
- site/assets/metrics.json : copy of training/metrics.json;
- site/assets/occupancy_logreg.json, site/assets/piece_prior.json : the two small weight files
  (models/, 541 B and 29 KB).

Standard library only, except the PNG files of the example photos (opencv-python, optional).
"""

import ast
import json
import os
import shutil
import sys

SITE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SITE)
MODULES = ["chessrules.py", "piece_inference.py", "replay.py", "logic.py", "occupancy.py", "robust_calibration.py"]
GLUE_FUNCTIONS = ["method_fr", "jpeg_data_url", "draw_input", "draw_top", "analyze_image", "game_positions",
                  "occupancy_of", "describe_event", "build_replay"]
GLUE_CONSTANTS = ["MAX_UPLOAD_BYTES", "MAX_SIDE", "MAX_TEXT", "MAX_PLIES", "EXAMPLES", "GAMES"]
WEIGHTS = ["occupancy_logreg.json", "piece_prior.json"]

GLUE_HEADER = '''"""GENERATED by site/sync_site.py from demo/app.py: do not edit (run python site/sync_site.py).

The functions below are copied verbatim from demo/app.py (FastAPI demo). Only this header differs:
HTTPException stands in for FastAPI's, and cv2 / occupancy / robust_calibration / MODEL / PRIOR are
set by web_demo.py (OpenCV is loaded only when a photo is analysed).
"""

import base64
import json
import os
import re
import time

import numpy as np

import chessrules
import piece_inference
import replay


class HTTPException(Exception):
    def __init__(self, status_code, detail):
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


cv2 = occupancy = robust_calibration = None
MODEL = PRIOR = None
GAMES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "games")

'''


def glue_source(app_path=None):
    """Header + the constants and functions of demo/app.py listed above, verbatim."""
    app_path = app_path or os.path.join(ROOT, "demo", "app.py")
    with open(app_path, encoding="utf-8") as f:
        src = f.read()
    tree = ast.parse(src)
    parts = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in GLUE_FUNCTIONS:
            parts[node.name] = ast.get_source_segment(src, node)
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) \
                and node.targets[0].id in GLUE_CONSTANTS:
            parts[node.targets[0].id] = ast.get_source_segment(src, node)
    missing = [n for n in GLUE_CONSTANTS + GLUE_FUNCTIONS if n not in parts]
    if missing:
        raise SystemExit(f"demo/app.py: not found {missing}")
    body = "\n".join(parts[n] for n in GLUE_CONSTANTS) + "\n\n\n" + "\n\n\n".join(parts[n] for n in GLUE_FUNCTIONS)
    return GLUE_HEADER + body + "\n"


def catalog(app_path=None):
    """EXAMPLES and GAMES of demo/app.py, as the page needs them (labels, notes, files)."""
    app_path = app_path or os.path.join(ROOT, "demo", "app.py")
    with open(app_path, encoding="utf-8") as f:
        tree = ast.parse(f.read())
    vals = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id in ("EXAMPLES", "GAMES"):
            vals[node.targets[0].id] = ast.literal_eval(node.value)
    return {"examples": [dict(e, url=f"assets/examples/{e['file']}", pixels=f"assets/examples/{e['id']}.png")
                         for e in vals["EXAMPLES"]],
            "games": [{"id": k, "label": v["label"], "note": v["note"], "file": v["file"]} for k, v in vals["GAMES"].items()]}


def main():
    py = os.path.join(SITE, "py")
    assets = os.path.join(SITE, "assets")
    ex_dst = os.path.join(assets, "examples")
    os.makedirs(os.path.join(ex_dst, "games"), exist_ok=True)
    os.makedirs(py, exist_ok=True)
    for m in MODULES:
        shutil.copyfile(os.path.join(ROOT, "src", m), os.path.join(py, m))
    with open(os.path.join(py, "demo_glue.py"), "w", encoding="utf-8") as f:
        f.write(glue_source())
    cat = catalog()
    ex_src = os.path.join(ROOT, "demo", "static", "examples")
    try:
        import cv2
    except ImportError:
        cv2 = None
    for e in cat["examples"]:
        shutil.copyfile(os.path.join(ex_src, e["file"]), os.path.join(ex_dst, e["file"]))
        png = os.path.join(ex_dst, f"{e['id']}.png")
        if cv2 is not None:
            cv2.imwrite(png, cv2.imread(os.path.join(ex_src, e["file"])), [cv2.IMWRITE_PNG_COMPRESSION, 9])
        elif not os.path.exists(png):
            print(f"warning: opencv-python missing, site/assets/examples/{e['id']}.png not written", file=sys.stderr)
    for g in cat["games"]:
        shutil.copyfile(os.path.join(ex_src, "games", g["file"]), os.path.join(ex_dst, "games", g["file"]))
    with open(os.path.join(assets, "catalog.json"), "w", encoding="utf-8") as f:
        json.dump(cat, f, ensure_ascii=False, indent=1)
        f.write("\n")
    shutil.copyfile(os.path.join(ROOT, "training", "metrics.json"), os.path.join(assets, "metrics.json"))
    for w in WEIGHTS:
        src = os.path.join(ROOT, "models", w)
        if os.path.exists(src):
            shutil.copyfile(src, os.path.join(assets, w))
        elif not os.path.exists(os.path.join(assets, w)):
            print(f"warning: models/{w} missing (models/ is not versioned); site/assets/{w} not updated", file=sys.stderr)
    files = sorted(f for f in os.listdir(py) if f.endswith(".py"))
    with open(os.path.join(py, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(files, f, indent=1)
        f.write("\n")
    print("site/py:", files)
    print("site/assets: catalog.json, metrics.json,", WEIGHTS, len(cat["examples"]), "photos,", len(cat["games"]), "games")


if __name__ == "__main__":
    main()
